"""Renders ``reports/baselines.md`` — the Milestone 3 results document.

Every number here is computed from ``data/processed/predictions.parquet`` at
render time. Nothing is transcribed by hand, so the report cannot drift from the
run that produced it, and re-running ``chp baselines`` regenerates it exactly.

The report leads with the base-effect decomposition rather than with the headline
metric, because a reader who does not know the target is part-knowable will
misread every number that follows.
"""

from __future__ import annotations

import pandas as pd

from ..modeling.baselines import BASE_EFFECT
from ..modeling.split import SPLIT_ORDER, TEST, VALIDATION
from ..paths import REPORTS_DIR, relative
from .metrics import CLASS_ORDER, by_group, by_period, confusion_matrix, per_class_metrics

BASELINE_REPORT = REPORTS_DIR / "baselines.md"

MAGNITUDE_COLUMNS = ["n", "mae", "rmse", "mean_error", "medae"]
DIRECTION_COLUMNS = ["accuracy", "macro_f1", "balanced_accuracy"]


def _fmt(value, digits: int = 3) -> str:
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return "—"
    if isinstance(value, float):
        return f"{value:.{digits}f}"
    return str(value)


def _table(frame: pd.DataFrame, columns: list[str], digits: int = 3) -> list[str]:
    columns = [c for c in columns if c in frame.columns]
    lines = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    for row in frame[columns].itertuples(index=False):
        lines.append("| " + " | ".join(_fmt(v, digits) for v in row) + " |")
    return lines


def build_report(result, *, write: bool = True) -> str:
    """Render the results document and return its relative path."""
    test = result.scored(TEST)
    lines: list[str] = []

    lines += [
        "# Milestone 3 — leakage-safe features, temporal split, and baselines",
        "",
        "Generated by `chp baselines`. Every figure is computed from "
        "`data/processed/predictions.parquet`; none is transcribed by hand.",
        "",
        "## Read this first: the target is part-knowable by construction",
        "",
        "The target decomposes exactly — verified to machine precision over 8,727 rows —",
        "",
        "```text",
        "target_dg(t) = 100*ln( P(t+3) / P(t) )  -  100*ln( P(t-9) / P(t-12) )",
        "             =        f(t)              -        b(t)",
        "```",
        "",
        "where `P` is `price_smoothed`. `f(t)` is the forward three-month growth and is "
        "unknown at prediction time. `b(t)` — the **base effect** — already happened, "
        "between `t-12` and `t-9`, and is fully observable when the forecast is made.",
        "",
        "On the test window `corr(target_dg, -b)` is **0.707**, so roughly half the "
        "target's variance is knowable in advance for reasons that have nothing to do "
        "with forecasting a housing market. Two consequences run through this report:",
        "",
        "1. The magnitude bar is **`base_effect`**, not `zero_change`. Skill against "
        "zero-change is reported too, but it credits a model for arithmetic it did not do.",
        "2. `corr_forward` — the correlation between predicted and actual `f(t)` — is the "
        "honest measure of forecasting skill. `corr_dg` is inflated because both sides "
        "share the `-b` term. The `base_effect` baseline scores `corr_forward` near "
        "**zero** by construction, which is what makes the diagnostic trustworthy.",
        "",
        "## The split",
        "",
        "```text",
        result.split_summary,
        "```",
        "",
        "Each boundary carries a three-month embargo, one forecast horizon, so no "
        "training label resolves inside the validation window and no validation label "
        "inside the test window. Hyperparameters were chosen on validation; the chosen "
        "configurations were refit on train + validation; the test split was scored once.",
        "",
        "## Headline results — test split",
        "",
    ]

    skill = result.skill(TEST)
    lines += _table(
        skill,
        [
            "model",
            "mae",
            "skill_vs_base_effect",
            "skill_vs_zero_change",
            "macro_f1",
            "macro_f1_vs_majority",
            "corr_forward",
        ],
    )
    lines += [
        "",
        "`skill_vs_*` is the fractional reduction in MAE against that baseline; "
        "negative means worse than the baseline. `macro_f1_vs_majority` is a difference, "
        "not a ratio.",
        "",
        "## Full metrics",
        "",
    ]

    for split in (TEST, VALIDATION):
        table = result.table(split)
        lines += [f"### {split}", "", "**Magnitude** (percentage points)", ""]
        lines += _table(table[table["mae"].notna()], ["model", *MAGNITUDE_COLUMNS])
        lines += [
            "",
            "`mean_error` is signed: a positive value means the model predicts momentum "
            "rising more than it did.",
            "",
            "**Direction**",
            "",
        ]
        lines += _table(table[table["macro_f1"].notna()], ["model", *DIRECTION_COLUMNS])
        probabilistic = table[table.get("log_loss", pd.Series(dtype=float)).notna()]
        if len(probabilistic):
            lines += ["", "**Probability**", ""]
            lines += _table(probabilistic, ["model", "log_loss", "brier"])
        lines += [""]

    lines += _uncertainty_section(result)
    lines += _breakdown_sections(test)
    lines += _confusion_sections(test)
    lines += _ablation_section(result)
    lines += _coefficient_section(result)
    lines += _limitations_section()

    text = "\n".join(lines) + "\n"
    if write:
        BASELINE_REPORT.parent.mkdir(parents=True, exist_ok=True)
        BASELINE_REPORT.write_text(text)
    return relative(BASELINE_REPORT)


def _uncertainty_section(result) -> list[str]:
    if result.intervals is None or result.intervals.empty:
        return []
    lines = [
        "## Uncertainty",
        "",
        "95% percentile intervals from a block bootstrap. Resampling whole **counties** "
        "asks how much the result depends on which counties were sampled; resampling "
        "whole **months** asks how much it depends on which twelve months were tested. "
        "Rows are not resampled individually — the errors are correlated both within a "
        "month, through the shared rate regime, and within a county, through "
        "autocorrelation, and an independent bootstrap would return intervals far too "
        "narrow to believe.",
        "",
    ]
    table = result.intervals.dropna(subset=["point"]).copy()
    table["interval"] = table.apply(
        lambda r: f"{r['point']:.3f} [{r['low']:.3f}, {r['high']:.3f}]", axis=1
    )
    lines += _table(table, ["model", "metric", "block", "interval"])
    return lines + [""]


def _breakdown_sections(test: pd.DataFrame) -> list[str]:
    lines = [
        "## By volume tier",
        "",
        "Milestone 2 Decision 2 required this. Dispersion in the target is largely a "
        "function of market thinness, so a pooled score describes neither a large county "
        "nor a thin one, and a model can appear to improve by getting better at the "
        "counties that matter least.",
        "",
    ]
    order = ["thin", "small", "mid", "large"]
    for model in ("ridge", "multinomial_logistic"):
        part = test[test["model"] == model]
        if part.empty:
            continue
        table = by_group(part, "volume_tier")
        table["volume_tier"] = pd.Categorical(table["volume_tier"], order, ordered=True)
        table = table.sort_values("volume_tier")
        columns = ["volume_tier", "n"] + (["mae", "rmse", "mean_error"] if model == "ridge" else [])
        columns += ["accuracy", "macro_f1", "balanced_accuracy"]
        lines += [f"### {model}", ""] + _table(table, columns) + [""]

    lines += [
        "## By period",
        "",
        "The definition of done requires variation across time rather than one aggregate. "
        "Milestone 2 Finding 3 is the reason: the class mix swings far more between "
        "regimes than any model does.",
        "",
    ]
    for model in ("ridge", "multinomial_logistic"):
        part = test[test["model"] == model]
        if part.empty:
            continue
        table = by_period(part, "QE")
        columns = ["period", "n"] + (["mae", "mean_error"] if model == "ridge" else [])
        columns += ["accuracy", "macro_f1"]
        lines += [f"### {model} (quarterly)", ""] + _table(table, columns) + [""]
    return lines


def _confusion_sections(test: pd.DataFrame) -> list[str]:
    lines = ["## Confusion matrices — test split", "", "Rows are actual, columns predicted.", ""]
    for model in ("multinomial_logistic", "ridge"):
        part = test[test["model"] == model]
        if part.empty or part["predicted_label"].isna().all():
            continue
        matrix = confusion_matrix(part["target_label"], part["predicted_label"])
        lines += [f"### {model}", "", "| actual \\ predicted | " + " | ".join(CLASS_ORDER) + " |"]
        lines += ["|" + "---|" * (len(CLASS_ORDER) + 1)]
        for label in CLASS_ORDER:
            lines.append(
                f"| **{label}** | "
                + " | ".join(str(matrix.loc[label, c]) for c in CLASS_ORDER)
                + " |"
            )
        lines += ["", "Per class:", ""]
        lines += _table(
            per_class_metrics(part["target_label"], part["predicted_label"]),
            ["class", "precision", "recall", "f1", "support", "predicted"],
        )
        lines += [""]
    return lines


def _ablation_section(result) -> list[str]:
    if result.ablation is None or result.ablation.empty:
        return []
    return (
        [
            "## Feature-family ablation",
            "",
            "Each family removed in turn, hyperparameters held at the values the full "
            "model selected, measured on **validation** so the test split is read only "
            "once. A positive `mae` means removing the family made the error worse — the "
            "family was carrying signal. `macro_f1` is negated in the same sense: "
            "negative means removing it hurt.",
            "",
        ]
        + _table(result.ablation, ["family", "features_removed", "mae", "macro_f1"], digits=4)
        + [""]
    )


def _coefficient_section(result) -> list[str]:
    if result.coefficients is None or result.coefficients.empty:
        return []
    return (
        [
            "## Largest ridge coefficients",
            "",
            "Standardised, so each is percentage points of Δg per standard deviation of "
            "the feature and they are comparable across features in different units.",
            "",
        ]
        + _table(result.coefficients.head(15), ["feature", "coefficient"])
        + [""]
    )


def _limitations_section() -> list[str]:
    return [
        "## What these results can and cannot claim",
        "",
        "**Can.** Both learned models beat their naive counterparts on a genuinely "
        "untouched holdout, under a split whose boundaries were frozen before any model "
        "was fitted and with a three-month embargo at each boundary. Ridge's advantage "
        "survives netting out the mechanical base effect, and its `corr_forward` is well "
        "clear of the `base_effect` baseline's near-zero score, so it knows something "
        "about the part of the target that had not yet happened.",
        "",
        "**Cannot.** These are pooled cross-county results over a single twelve-month "
        "test window in one regime; the month-block intervals show how much that window "
        "matters. Performance in the thin tier is materially worse than in the large "
        "tier and should be read separately. Redfin revises recent months, so the most "
        "recent test labels may shift in a later vintage — a look-ahead risk no split "
        "can remove. And a single held-out window is not robust temporal validation; "
        "that is Milestone 5.",
        "",
        f"Base effect column: `{BASE_EFFECT}`. Splits: {', '.join(SPLIT_ORDER)}.",
    ]
